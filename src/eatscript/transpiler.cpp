std::string Transpiler::emitIndent() const {
    return std::string(indentLevel_ * 4, ' ');
}

std::string Transpiler::transpileSource(const std::string& source, const std::string& pluginId,
                                        const std::string& pluginName) {
    Lexer lexer(source);
    auto tokens = lexer.tokenize();
    Parser parser(std::move(tokens));
    auto prog = parser.parse();
    if (!prog) return "// Parsing failed\n";
    return transpile(*prog, pluginId, pluginName);
}

std::string Transpiler::transpile(const Program& program, const std::string& pluginId,
                                  const std::string& pluginName) {
    processBodyCode_.clear();

    // Scan for process function
    for (const auto& stmt : program.statements) {
        auto* func = ast_cast<FunctionDef>(stmt.get());
        if (func && func->name == "process") {
            inProcessFunction_ = true;
            indentLevel_ = 2;
            for (const auto& s : func->body) {
                transpileStmt(s.get());
            }
            inProcessFunction_ = false;
        }
    }

    std::ostringstream ss;
    ss << "// Generated by Eatsbits Eatscript AOT Transpiler\n";
    ss << "#include \"eatsbits/abi/eats_plugin_abi.h\"\n";
    ss << "#include <cmath>\n";
    ss << "#include <numbers>\n";
    ss << "#include <algorithm>\n\n";

    ss << "struct PluginInstance_" << pluginId << " {\n";
    ss << "    double sampleRate{48000.0};\n";
    ss << "    float params[16]{};\n";
    ss << "    double currentFreq{440.0};\n";
    ss << "    uint8_t currentNote{69};\n";
    ss << "    uint64_t sampleCount{0};\n";
    ss << "    bool active{false};\n";
    ss << "};\n\n";

    ss << "extern \"C\" {\n\n";

    // create_instance
    ss << "static void* create_instance_" << pluginId << "(double sampleRate) {\n";
    ss << "    auto* inst = new PluginInstance_" << pluginId << "();\n";
    ss << "    inst->sampleRate = sampleRate;\n";
    ss << "    return inst;\n";
    ss << "}\n\n";

    // destroy_instance
    ss << "static void destroy_instance_" << pluginId << "(void* instance) {\n";
    ss << "    delete static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "}\n\n";

    // set_param
    ss << "static void set_param_" << pluginId << "(void* instance, uint32_t paramId, float value) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    if (paramId < 16) inst->params[paramId] = value;\n";
    ss << "}\n\n";

    // note_on
    ss << "static void note_on_" << pluginId << "(void* instance, uint8_t pitch, float velocity) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    inst->currentNote = pitch;\n";
    ss << "    inst->currentFreq = 440.0 * std::pow(2.0, (static_cast<double>(pitch) - 69.0) / 12.0);\n";
    ss << "    inst->sampleCount = 0;\n";
    ss << "    inst->active = true;\n";
    ss << "}\n\n";

    // note_off
    ss << "static void note_off_" << pluginId << "(void* instance, uint8_t pitch) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    if (inst->currentNote == pitch) inst->active = false;\n";
    ss << "}\n\n";

    // process
    ss << "static void process_" << pluginId << "(void* instance, const EatsAudioBuffer* buffer) {\n";
    ss << "    auto* inst = static_cast<PluginInstance_" << pluginId << "*>(instance);\n";
    ss << "    if (!inst->active) return;\n";
    ss << "    float* outL = buffer->outputs[0];\n";
    ss << "    float* outR = (buffer->numChannels > 1) ? buffer->outputs[1] : outL;\n";
    ss << "    const double freq = inst->currentFreq;\n";
    ss << "    const double note = static_cast<double>(inst->currentNote);\n";
    ss << "    const double sampleRate = inst->sampleRate;\n\n";

    ss << "    for (uint32_t i = 0; i < buffer->numSamples; ++i) {\n";
    ss << "        const double time = static_cast<double>(inst->sampleCount++) / sampleRate;\n";
    ss << "        double sample = 0.0;\n";
    ss << processBodyCode_;
    ss << "        outL[i] += static_cast<float>(sample);\n";
    ss << "        outR[i] += static_cast<float>(sample);\n";
    ss << "    }\n";
    ss << "}\n\n";

    // Plugin Descriptor
    ss << "const EatsPluginDescriptor g_plugin_" << pluginId << " = {\n";
    ss << "    \"" << pluginId << "\",\n";
    ss << "    \"" << pluginName << "\",\n";
    ss << "    16,\n";
    ss << "    create_instance_" << pluginId << ",\n";
    ss << "    destroy_instance_" << pluginId << ",\n";
    ss << "    process_" << pluginId << ",\n";
    ss << "    set_param_" << pluginId << ",\n";
    ss << "    note_on_" << pluginId << ",\n";
    ss << "    note_off_" << pluginId << "\n";
    ss << "};\n\n";

    ss << "} // extern \"C\"\n";

    return ss.str();
}

void Transpiler::transpileStmt(const Stmt* stmt) {
    if (!stmt) return;
    switch (stmt->kind) {
        case StmtKind::Expr:
            visit(static_cast<ExprStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::Assign:
            visit(static_cast<AssignStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::IndexAssign:
            visit(static_cast<IndexAssignStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::Return:
            visit(static_cast<ReturnStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::If:
            visit(static_cast<IfStmt*>(const_cast<Stmt*>(stmt)));
            break;
        case StmtKind::FunctionDef:
            visit(static_cast<FunctionDef*>(const_cast<Stmt*>(stmt)));
            break;
    }
}

void Transpiler::transpileExpr(const Expr* expr) {
    if (!expr) return;
    switch (expr->kind) {
        case ExprKind::Number:
            visit(static_cast<NumberLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::String:
            visit(static_cast<StringLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Boolean:
            visit(static_cast<BooleanLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Identifier:
            visit(static_cast<IdentifierExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Member:
            visit(static_cast<MemberExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Binary:
            visit(static_cast<BinaryExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Unary:
            visit(static_cast<UnaryExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Call:
            visit(static_cast<CallExpr*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::List:
            visit(static_cast<ListLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Dict:
            visit(static_cast<DictLiteral*>(const_cast<Expr*>(expr)));
            break;
        case ExprKind::Index:
            visit(static_cast<IndexExpr*>(const_cast<Expr*>(expr)));
            break;
    }
}

void Transpiler::visit(NumberLiteral* node) {
    output_ += std::to_string(node->value);
}

void Transpiler::visit(StringLiteral* node) {
    output_ += "\"" + node->value + "\"";
}

void Transpiler::visit(BooleanLiteral* node) {
    output_ += node->value ? "true" : "false";
}

void Transpiler::visit(IdentifierExpr* node) {
    if (node->name == "pi") {
        output_ += "std::numbers::pi_v<double>";
    } else {
        output_ += node->name;
    }
}

void Transpiler::visit(MemberExpr* node) {
    auto* objId = ast_cast<IdentifierExpr>(node->object.get());
    if (objId && objId->name == "math" && node->member == "pi") {
        output_ += "std::numbers::pi_v<double>";
    } else {
        transpileExpr(node->object.get());
        output_ += "." + node->member;
    }
}

void Transpiler::visit(BinaryExpr* node) {
    output_ += "(";
    transpileExpr(node->left.get());
    switch (node->op) {
        case TokenType::Plus: output_ += " + "; break;
        case TokenType::Minus: output_ += " - "; break;
        case TokenType::Multiply: output_ += " * "; break;
        case TokenType::Divide: output_ += " / "; break;
        case TokenType::Power:
            // Rewrite a ** b as std::pow(a, b)
            output_ = "std::pow(" + output_;
            transpileExpr(node->right.get());
            output_ += ")";
            return;
        default: output_ += " + "; break;
    }
    transpileExpr(node->right.get());
    output_ += ")";
}

void Transpiler::visit(UnaryExpr* node) {
    if (node->op == TokenType::Minus) output_ += "-";
    transpileExpr(node->operand.get());
}

void Transpiler::visit(CallExpr* node) {
    auto* mem = ast_cast<MemberExpr>(node->callee.get());
    if (mem) {
        auto* objId = ast_cast<IdentifierExpr>(mem->object.get());
        if (objId && objId->name == "math") {
            output_ += "std::" + mem->member + "(";
            for (size_t i = 0; i < node->args.size(); ++i) {
                if (i > 0) output_ += ", ";
                transpileExpr(node->args[i].get());
            }
            output_ += ")";
            return;
        } else if (objId && objId->name == "params" && mem->member == "get") {
            if (!node->args.empty()) {
                auto* numLit = ast_cast<NumberLiteral>(node->args[0].get());
                if (numLit) {
                    output_ += (inClapMode_ ? "params_[" : "inst->params[") + std::to_string(static_cast<int>(numLit->value)) + "]";
                    return;
                }
            }
            output_ += inClapMode_ ? "params_[0]" : "inst->params[0]";
            return;
        } else if (objId && (objId->name == "eat" || objId->name == "dsp") && mem->member == "param") {
            if (!node->args.empty()) {
                auto* strLit = ast_cast<StringLiteral>(node->args[0].get());
                if (strLit && currentScanResult_) {
                    auto clapDefs = currentScanResult_->generateClapParamDefs();
                    for (size_t idx = 0; idx < clapDefs.size(); ++idx) {
                        if (clapDefs[idx].name == strLit->value) {
                            output_ += (inClapMode_ ? "params_[" : "inst->params[") + std::to_string(idx) + "]";
                            return;
                        }
                    }
                }
            }
            output_ += inClapMode_ ? "params_[0]" : "inst->params[0]";
            return;
        }
    }

    transpileExpr(node->callee.get());
    output_ += "(";
    for (size_t i = 0; i < node->args.size(); ++i) {
        if (i > 0) output_ += ", ";
        transpileExpr(node->args[i].get());
    }
    output_ += ")";
}

void Transpiler::visit(ListLiteral* node) {
    if (!node->elements.empty()) {
        transpileExpr(node->elements[0].get());
    }
}

void Transpiler::visit(DictLiteral* /*node*/) {}

void Transpiler::visit(IndexExpr* node) {
    if (!node) return;
    transpileExpr(node->object.get());
    output_ += "[";
    transpileExpr(node->index.get());
    output_ += "]";
}

void Transpiler::visit(ExprStmt* node) {
    output_.clear();
    transpileExpr(node->expression.get());
    processBodyCode_ += emitIndent() + output_ + ";\n";
}

void Transpiler::visit(AssignStmt* node) {
    output_.clear();
    transpileExpr(node->value.get());
    processBodyCode_ += emitIndent() + "double " + node->variableName + " = " + output_ + ";\n";
}

void Transpiler::visit(IndexAssignStmt* node) {
    output_.clear();
    std::string keyOutput;
    transpileExpr(node->index.get());
    keyOutput = output_;
    output_.clear();
    transpileExpr(node->value.get());
    processBodyCode_ += emitIndent() + node->variableName + "[" + keyOutput + "] = " + output_ + ";\n";
}

void Transpiler::visit(ReturnStmt* node) {
    output_.clear();
    if (node->value) {
        transpileExpr(node->value.get());
        processBodyCode_ += emitIndent() + "sample = " + output_ + ";\n";
    }
}

void Transpiler::visit(IfStmt* node) {
    output_.clear();
    transpileExpr(node->condition.get());
    processBodyCode_ += emitIndent() + "if (" + output_ + ") {\n";
    indentLevel_++;
    for (const auto& s : node->thenBranch) {
        transpileStmt(s.get());
    }
    indentLevel_--;
    processBodyCode_ += emitIndent() + "}\n";
}

void Transpiler::visit(FunctionDef* /*node*/) {}

std::string Transpiler::emitClapPluginEntry(const Program& program, const DependencyScanResult& scanResult) {
    inClapMode_ = true;
    currentScanResult_ = &scanResult;
    processBodyCode_.clear();

    // Scan for process function
    for (const auto& stmt : program.statements) {
        auto* func = ast_cast<FunctionDef>(stmt.get());
        if (func && func->name == "process") {
            inProcessFunction_ = true;
            indentLevel_ = 3;
            for (const auto& s : func->body) {
                transpileStmt(s.get());
            }
            inProcessFunction_ = false;
        }
    }

    auto clapParams = scanResult.generateClapParamDefs();
    const size_t numParams = clapParams.size();

    std::ostringstream ss;
    ss << "// ==============================================================================\n";
    ss << "// Generated by Eatsbits Eatscript AOT Transpiler (CLAP Target)\n";
    ss << "// Plugin ID: " << scanResult.metadata.id << "\n";
    ss << "// Plugin Name: " << scanResult.metadata.name << "\n";
    ss << "// Category: " << scanResult.metadata.category << "\n";
    ss << "// ==============================================================================\n\n";

    ss << "#include \"eatsbits/export/clap/clap_plugin_shell.hpp\"\n";
    ss << "#include <cmath>\n";
    ss << "#include <numbers>\n";
    ss << "#include <algorithm>\n";
    ss << "#include <array>\n";
    ss << "#include <cstdio>\n";
    ss << "#include <cstdlib>\n";
    ss << "#include <cstring>\n";
    ss << "#include <string>\n\n";

    // Discovered DSP Module Headers
    if (!scanResult.dependencies.headers.empty()) {
        ss << "// Discovered DSP Module Headers\n";
        for (const auto& hdr : scanResult.dependencies.headers) {
            ss << "#include \"" << hdr << "\"\n";
        }
        ss << "\n";
    }

    std::string safePluginId = scanResult.metadata.id.empty() ? "eats_patch" : scanResult.metadata.id;
    for (char& c : safePluginId) {
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') c = '_';
    }

    std::string adapterClassName = "GeneratedPatchAdapter_" + safePluginId;

    ss << "namespace eatsbits::generated {\n\n";
    ss << "class " << adapterClassName << " {\n";
    ss << "public:\n";

    // Descriptor
    ss << "    static const clap_plugin_descriptor_t* getDescriptor() noexcept {\n";
    ss << "        static const char* const s_features[] = {\n";
    if (scanResult.metadata.category == "audio-effect" || scanResult.metadata.category == "effect" || scanResult.metadata.category == "fx") {
        ss << "            CLAP_PLUGIN_FEATURE_AUDIO_EFFECT,\n";
    } else {
        ss << "            CLAP_PLUGIN_FEATURE_INSTRUMENT,\n";
        ss << "            CLAP_PLUGIN_FEATURE_SYNTHESIZER,\n";
    }
    ss << "            CLAP_PLUGIN_FEATURE_STEREO,\n";
    ss << "            nullptr\n";
    ss << "        };\n\n";

    ss << "        static const clap_plugin_descriptor_t s_desc = {\n";
    ss << "            .clap_version = CLAP_VERSION,\n";
    ss << "            .id = \"" << (scanResult.metadata.id.empty() ? "com.maddestlabs.eatsbits.patch" : scanResult.metadata.id) << "\",\n";
    ss << "            .name = \"" << (scanResult.metadata.name.empty() ? "Eatscript Patch" : scanResult.metadata.name) << "\",\n";
    ss << "            .vendor = \"" << (scanResult.metadata.vendor.empty() ? "Maddest Labs" : scanResult.metadata.vendor) << "\",\n";
    ss << "            .url = \"https://github.com/maddestlabs/eatsbits\",\n";
    ss << "            .manual_url = \"\",\n";
    ss << "            .support_url = \"https://github.com/maddestlabs/eatsbits/issues\",\n";
    ss << "            .version = \"" << (scanResult.metadata.version.empty() ? "1.0.0" : scanResult.metadata.version) << "\",\n";
    ss << "            .description = \"" << scanResult.metadata.description << "\",\n";
    ss << "            .features = s_features,\n";
    ss << "        };\n";
    ss << "        return &s_desc;\n";
    ss << "    }\n\n";

    // Param count and defs
    ss << "    static uint32_t getParamCount() noexcept {\n";
    ss << "        return " << numParams << ";\n";
    ss << "    }\n\n";

    if (numParams == 0) {
        ss << "    static const eatsbits::export_clap::ClapParamDef& getParamDef(uint32_t /*index*/) noexcept {\n";
        ss << "        static const eatsbits::export_clap::ClapParamDef s_fallback{};\n";
        ss << "        return s_fallback;\n";
        ss << "    }\n\n";
    } else {
        ss << "    static const eatsbits::export_clap::ClapParamDef& getParamDef(uint32_t index) noexcept {\n";
        ss << "        static const std::array<eatsbits::export_clap::ClapParamDef, " << numParams << "> s_defs = {{\n";
        for (const auto& p : clapParams) {
            ss << "            {" << p.id << ", \"" << p.name << "\", \"" << p.module << "\", "
               << p.minValue << ", " << p.maxValue << ", " << p.defaultValue << ", 0x"
               << std::hex << p.flags << std::dec << "},\n";
        }
        ss << "        }};\n";
        ss << "        return (index < s_defs.size()) ? s_defs[index] : s_defs[0];\n";
        ss << "    }\n\n";
    }

    // Lifecycle
    ss << "    " << adapterClassName << "() noexcept {\n";
    if (numParams > 0) {
        ss << "        for (uint32_t i = 0; i < getParamCount(); ++i) {\n";
        ss << "            params_[i] = static_cast<float>(getParamDef(i).defaultValue);\n";
        ss << "            setParamValue(i, getParamDef(i).defaultValue);\n";
        ss << "        }\n";
    }
    ss << "    }\n\n";

    // SetSampleRate
    ss << "    void setSampleRate(double sampleRate) noexcept {\n";
    ss << "        sampleRate_ = sampleRate;\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        tb303_.setSampleRate(static_cast<float>(sampleRate));\n";
    }
    ss << "    }\n\n";

    // Reset
    ss << "    void reset() noexcept {\n";
    ss << "        sampleCount_ = 0;\n";
    ss << "        active_ = false;\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        tb303_.reset();\n";
    }
    ss << "    }\n\n";

    // NoteOn
    ss << "    void noteOn(uint8_t note, float velocity, bool isSlide = false, bool isAccent = false) noexcept {\n";
    ss << "        currentNote_ = note;\n";
    ss << "        currentVelocity_ = velocity;\n";
    ss << "        currentFreq_ = 440.0 * std::pow(2.0, (static_cast<double>(note) - 69.0) / 12.0);\n";
    ss << "        sampleCount_ = 0;\n";
    ss << "        active_ = true;\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        tb303_.noteOn(note, velocity, isSlide, isAccent);\n";
    }
    ss << "    }\n\n";

    // NoteOff
    ss << "    void noteOff(uint8_t note = 0, float /*velocity*/ = 0.0f) noexcept {\n";
    ss << "        if (note == 0 || currentNote_ == note) {\n";
    ss << "            active_ = false;\n";
    ss << "        }\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        tb303_.noteOff();\n";
    }
    ss << "    }\n\n";

    // IsActive
    ss << "    [[nodiscard]] bool isActive() const noexcept {\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        return tb303_.isActive();\n";
    } else {
        ss << "        return active_;\n";
    }
    ss << "    }\n\n";

    // GetParamValue
    ss << "    [[nodiscard]] double getParamValue(clap_id id) const noexcept {\n";
    ss << "        if (id < params_.size()) {\n";
    ss << "            return params_[id];\n";
    ss << "        }\n";
    ss << "        return 0.0;\n";
    ss << "    }\n\n";

    // SetParamValue
    ss << "    void setParamValue(clap_id id, double val) noexcept {\n";
    ss << "        if (id < params_.size()) {\n";
    ss << "            params_[id] = static_cast<float>(val);\n";
    ss << "        }\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        switch (id) {\n";
        ss << "            case 0: tb303_.setCutoff(static_cast<float>(val)); break;\n";
        ss << "            case 1: tb303_.setResonance(static_cast<float>(val)); break;\n";
        ss << "            case 2: tb303_.setEnvMod(static_cast<float>(val)); break;\n";
        ss << "            case 3: tb303_.setDecay(static_cast<float>(val)); break;\n";
        ss << "            case 4: tb303_.setAccent(static_cast<float>(val)); break;\n";
        ss << "            case 5: tb303_.setWaveform(static_cast<float>(val)); break;\n";
        ss << "            case 6: tb303_.setOverdrive(static_cast<float>(val)); break;\n";
        ss << "            case 7: tb303_.setTuning(static_cast<float>(val)); break;\n";
        ss << "            case 8: tb303_.setOctave(static_cast<int>(std::round(val))); break;\n";
        ss << "            case 9: tb303_.setSubVolume(static_cast<float>(val)); break;\n";
        ss << "            case 10: tb303_.setSubWaveform(static_cast<float>(val)); break;\n";
        ss << "            case 11: tb303_.setGlideCurve(static_cast<float>(val)); break;\n";
        ss << "            default: break;\n";
        ss << "        }\n";
    }
    ss << "    }\n\n";

    // ValueToText & TextToValue
    ss << "    bool valueToText(clap_id /*id*/, double val, char* buf, uint32_t cap) const noexcept {\n";
    ss << "        if (!buf || cap == 0) return false;\n";
    ss << "        std::snprintf(buf, cap, \"%.2f\", val);\n";
    ss << "        return true;\n";
    ss << "    }\n\n";

    ss << "    bool textToValue(clap_id /*id*/, const char* text, double* out) const noexcept {\n";
    ss << "        if (!text || !out) return false;\n";
    ss << "        char* end = nullptr;\n";
    ss << "        *out = std::strtod(text, &end);\n";
    ss << "        return (end != text);\n";
    ss << "    }\n\n";

    // ProcessBlock
    ss << "    void processBlock(float* outL, float* outR, size_t numFrames) noexcept {\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "        for (size_t i = 0; i < numFrames; ++i) {\n";
        ss << "            const float s = tb303_.processSample();\n";
        ss << "            outL[i] += s;\n";
        ss << "            outR[i] += s;\n";
        ss << "        }\n";
    } else {
        ss << "        if (!active_) return;\n";
        ss << "        const double freq = currentFreq_;\n";
        ss << "        const double note = static_cast<double>(currentNote_);\n";
        ss << "        const double velocity = static_cast<double>(currentVelocity_);\n";
        ss << "        const double sampleRate = sampleRate_;\n";
        for (const auto& p : clapParams) {
            std::string safeName = p.name;
            for (char& c : safeName) {
                if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') c = '_';
            }
            if (!safeName.empty() && !std::isdigit(static_cast<unsigned char>(safeName[0]))) {
                ss << "        const double " << safeName << " = params_[" << p.id << "];\n";
            }
        }
        ss << "        for (size_t i = 0; i < numFrames; ++i) {\n";
        ss << "            const double time = static_cast<double>(sampleCount_++) / sampleRate_;\n";
        ss << "            double sample = 0.0;\n";
        if (!processBodyCode_.empty()) {
            ss << processBodyCode_;
        }
        ss << "            outL[i] += static_cast<float>(sample);\n";
        ss << "            outR[i] += static_cast<float>(sample);\n";
        ss << "        }\n";
    }
    ss << "    }\n\n";

    // Member variables
    ss << "private:\n";
    if (scanResult.dispatchTarget == NativeDispatchTarget::TB303) {
        ss << "    eatsbits::dsp::Tb303Core tb303_;\n";
    }
    ss << "    double sampleRate_{48000.0};\n";
    ss << "    uint64_t sampleCount_{0};\n";
    ss << "    uint8_t currentNote_{69};\n";
    ss << "    float currentVelocity_{0.8f};\n";
    ss << "    double currentFreq_{440.0};\n";
    ss << "    bool active_{false};\n";
    ss << "    std::array<float, " << std::max<size_t>(1, numParams) << "> params_{};\n";

    ss << "};\n\n";
    ss << "} // namespace eatsbits::generated\n\n";

    // Export macro
    ss << "EATS_CLAP_EXPORT_PLUGIN(eatsbits::generated::" << adapterClassName << ")\n";

    inClapMode_ = false;
    currentScanResult_ = nullptr;
    return ss.str();
}

std::string Transpiler::transpileClap(const std::string& source) {
    auto scanResult = DependencyScanner::scan(source);
    Lexer lexer(source);
    auto tokens = lexer.tokenize();
    Parser parser(std::move(tokens));
    auto prog = parser.parse();
    if (!prog) {
        prog = std::make_unique<Program>();
    }
    return emitClapPluginEntry(*prog, scanResult);
}

